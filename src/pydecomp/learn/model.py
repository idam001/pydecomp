"""pydecomp - the trained decoder ranking.

A one-vs-rest linear model: for every decoder name there is a weight vector over
the features in :mod:`pydecomp.learn.features`, and the ranking is the dot
product.  Weights live in ``weights.py`` next to this file, written by
``tools/train_learn.py`` from the corpus.  They are plain integers, so the model
is inspectable, diffable, and costs nothing to load.

Two rules this module keeps:

* ranking only reorders candidates - no decoder is ever skipped, so a bad
  ranking can cost time but cannot cost a recovery;
* with no weights, or with a blob the features cannot describe, the registry
  order stands.  Learning is an accelerator, never a dependency.
"""
from __future__ import annotations

from .features import FEATURE_NAMES, vector

try:                                                 # generated by the trainer
    from .weights import TRAINED_CLASSES, TRAINED_DIGEST, TRAINED_WEIGHTS
except ImportError:                                  # a checkout without training
    TRAINED_CLASSES = ()
    TRAINED_WEIGHTS = {}
    TRAINED_DIGEST = ""


def trained() -> bool:
    """Is there a trained ranking in this build?"""
    return bool(TRAINED_WEIGHTS)


def score(name: str, features: tuple[int, ...]) -> int:
    """The model's vote for ``name`` on these features (0 when not trained)."""
    weights = TRAINED_WEIGHTS.get(name)
    if not weights:
        return 0
    return sum(weight * value for weight, value in zip(weights, features))


def rank(names, blob: bytes) -> list[str]:
    """Order ``names`` for this blob: most likely decoder first.

    Ties keep the caller's order, so the result is deterministic and a ranking
    that knows nothing about a blob degrades exactly to the registry order.
    """
    order = list(names)
    if not TRAINED_WEIGHTS or not order:
        return order
    features = vector(blob)
    votes = {name: score(name, features) for name in order}
    indexed = list(enumerate(order))
    indexed.sort(key=lambda pair: (-votes[pair[1]], pair[0]))
    return [name for _position, name in indexed]


def fit(examples, classes, epochs: int = 12) -> dict[str, list[int]]:
    """Train the ranking.  Averaged perceptron, deterministic, no dependencies.

    ``examples`` is a sequence of ``(blob, {names that open it})``.  Every epoch
    visits the examples in the given order; a wrong top vote moves weight towards
    a true class and away from the wrong one.
    """
    weights = {name: [0] * len(FEATURE_NAMES) for name in classes}
    totals = {name: [0] * len(FEATURE_NAMES) for name in classes}
    steps = 0
    for _epoch in range(epochs):
        for blob, live in examples:
            if not live:
                continue
            features = vector(blob)
            best, best_vote = None, None
            for name in classes:
                vote = sum(weight * value
                           for weight, value in zip(weights[name], features))
                if best_vote is None or vote > best_vote:
                    best, best_vote = name, vote
            if best in live:
                steps += 1
                for name in classes:
                    row, acc = weights[name], totals[name]
                    for index, value in enumerate(features):
                        acc[index] += row[index]
                continue
            target = sorted(live)[0]
            for name, sign in ((target, 1), (best, -1)):
                row = weights[name]
                for index, value in enumerate(features):
                    row[index] += sign * value
            steps += 1
            for name in classes:
                row, acc = weights[name], totals[name]
                for index, value in enumerate(features):
                    acc[index] += row[index]
    if steps:
        for name in classes:
            row, acc = weights[name], totals[name]
            for index in range(len(row)):
                row[index] = int(round(acc[index] / steps))
    return weights
