#!/usr/bin/env python3
"""Build ``dist/pydecomp.py`` — the whole package as one runnable file.

The package layout is what you develop in; this single file is what you copy
to a phone, a jump host or a Termux session and run with nothing but a Python
interpreter.  There is no installer, no ``pip`` and no site-packages step:

    python3 pydecomp.py sample.py

How it works
------------
Every module of ``src/pydecomp`` is read, zlib-compressed and base85-encoded
into one string.  At start-up the blob is inflated into a ``{module: source}``
mapping and a meta-path finder serves those sources to :mod:`importlib`, so
the package imports exactly as it does from ``src/`` — same module names, same
relative imports, same tracebacks (attributed to ``<pydecomp:...>`` frames).

Nothing from the sample is ever executed while building or running the bundle;
``compile()`` here only compiles pydecomp's own sources.

Usage
-----
    python3 tools/build_single.py            # write dist/pydecomp.py
    python3 tools/build_single.py --check    # fail if it is stale/short
    python3 tools/build_single.py --out /tmp/pydecomp.py
"""
from __future__ import annotations

import argparse
import base64
import json
import pathlib
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "pydecomp"
DEFAULT_OUT = ROOT / "dist" / "pydecomp.py"


def version() -> str:
    for line in (SRC / "limits.py").read_text(encoding="utf-8").splitlines():
        if line.startswith("__version__"):
            return line.split("=", 1)[1].strip().strip("\"'")
    raise SystemExit("cannot find __version__ in limits.py")


def collect() -> tuple[dict[str, str], set[str]]:
    """Every module of the package as ``{dotted name: source}`` plus packages."""
    modules: dict[str, str] = {}
    packages: set[str] = set()
    for path in sorted(SRC.rglob("*.py")):
        parts = list(path.relative_to(SRC).with_suffix("").parts)
        if parts[-1] == "__init__":
            parts.pop()                                     # package body
            packages.add(".".join(["pydecomp", *parts]))
        modules[".".join(["pydecomp", *parts])] = path.read_text(encoding="utf-8")
    return modules, packages


def payload() -> bytes:
    """The packed module table, as JSON ready for compression."""
    modules, packages = collect()
    return json.dumps({"modules": modules, "packages": sorted(packages)},
                      sort_keys=True, separators=(",", ":")).encode("utf-8")


PREAMBLE = '''#!/usr/bin/env python3
# pydecomp {version} - single-file build.  Generated by tools/build_single.py;
# edit the package under src/pydecomp and rebuild rather than patching this file.
#
# Static Python deobfuscator: recovers readable source from packed, encoded or
# compiled Python without ever executing the sample.  Pure standard library,
# so a Termux shell with CPython 3.9+ is enough:
#
#     python3 pydecomp.py suspicious.py
#
"""pydecomp {version} - one file, no install, no execution of the sample."""
import base64 as _b64
import importlib as _importlib
import importlib.abc as _abc
import importlib.machinery as _machinery
import json as _json
import sys as _sys
import zlib as _zlib

__version__ = {version!r}

_BLOB = (
{blob}
)


def _unpack():
    raw = _zlib.decompress(_b64.b85decode(_BLOB.encode("ascii")))
    return _json.loads(raw.decode("utf-8"))


_PAYLOAD = _unpack()
_SOURCES = _PAYLOAD["modules"]
_PACKAGES = set(_PAYLOAD["packages"])


class _BundleLoader(_abc.Loader):
    """Serve a module body straight out of the bundle."""

    def create_module(self, spec):
        return None

    def exec_module(self, module):
        source = _SOURCES[module.__name__]
        code = compile(source, "<pydecomp:%s>" % module.__name__, "exec")
        exec(code, module.__dict__)


class _BundleFinder(_abc.MetaPathFinder):
    """Resolve ``pydecomp.*`` imports from the packed sources."""

    def find_spec(self, fullname, path=None, target=None):
        if fullname not in _SOURCES:
            return None
        spec = _machinery.ModuleSpec(fullname, _BundleLoader(),
                                     is_package=fullname in _PACKAGES)
        if fullname in _PACKAGES:
            spec.submodule_search_locations = []
        return spec


if not any(isinstance(finder, _BundleFinder) for finder in _sys.meta_path):
    _sys.meta_path.insert(0, _BundleFinder())


def main(argv=None):
    """Run the command line interface from the bundled package."""
    from pydecomp.cli import main as _cli_main
    return _cli_main(argv)


if __name__ == "__main__":
    _sys.exit(main())
'''


def build(out: pathlib.Path, level: int = 9) -> int:
    raw = payload()
    blob = base64.b85encode(zlib.compress(raw, level)).decode("ascii")
    wrapped = "\n".join('    "%s"' % blob[i:i + 96]
                         for i in range(0, len(blob), 96))
    text = PREAMBLE.format(version=version(), blob=wrapped)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    out.chmod(0o755)
    return len(text.encode("utf-8"))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="output path")
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if the bundle is missing or stale")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists():
            print(f"missing {out}")
            return 1
        fresh = out.read_text(encoding="utf-8")
        raw = payload()
        blob = base64.b85encode(zlib.compress(raw, 9)).decode("ascii")
        if blob not in fresh.replace("\n", "").replace('"', "").replace("    ", ""):
            print(f"stale {out}: rebuild with tools/build_single.py")
            return 1
        if not args.quiet:
            print(f"ok {out} {out.stat().st_size:,} B")
        return 0
    size = build(out)
    if not args.quiet:
        print(f"wrote {out}  {size:,} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
